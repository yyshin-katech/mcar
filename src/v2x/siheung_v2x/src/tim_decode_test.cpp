void print_hex_dump(const uint8_t* data, size_t len, size_t max_bytes = 64) {
    for (size_t i = 0; i < len && i < max_bytes; i++) {
        if (i % 16 == 0) printf("\n%04zx: ", i);
        printf("%02x ", data[i]);
    }
    printf("\n");
}

